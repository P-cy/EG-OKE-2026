# ช่องที่ต้องมีค่าก่อนจะเริ่มใช้งานได้ — (คีย์ใน user doc, ชื่อที่คนอ่านเข้าใจ)
#
# ★ ไม่มี instagram_handle ในนี้ และห้ามใส่กลับเข้ามา
#   เคยบังคับกรอก ซึ่งแปลว่าคนที่ไม่มี IG จะผ่าน onboarding ไม่ได้
#   → ไม่ได้บัตร → เช็คอินไม่ได้ = ติดตายอยู่หน้าประตูตั้งแต่ยังไม่เข้างาน
#   ชื่อ IG ถูกถามตอน "จะส่งรูปขึ้นจอ" เท่านั้น (หน้า /ig) ซึ่งเป็นจังหวะที่
#   คนกรอกเองอยู่แล้วและมีเหตุผลให้กรอก
REQUIRED_FIELDS: tuple[tuple[str, str], ...] = (
    ("display_name", "ชื่อเล่น"),
    ("faculty", "คณะ"),
    ("department", "สาขาวิชา"),
    ("student_id", "รหัสนักศึกษา"),
)


def missing_fields(doc: dict) -> list[str]:
    """ช่องที่ยังว่างอยู่ — คืนเป็นชื่อไทยไว้เอาไปบอกผู้ใช้ตรงๆ"""
    return [label for key, label in REQUIRED_FIELDS if not doc.get(key)]


def needs_onboarding(doc: dict) -> bool:
    """ต้องส่งไปหน้า /onboarding ไหม"""
    # ยังไม่เคยยอมรับเงื่อนไข — ทุกคนต้องผ่านด่านนี้
    if not doc.get("consent", {}).get("tos"):
        return True

    # ★ คนที่กรอกไว้ก่อนระบบจะขอครบ ต้องถูกดึงกลับมากรอกให้ครบ
    #   ไม่งั้นข้อมูลจะขาดเฉพาะคนที่สมัครช่วงแรก แล้วสรุปยอดรายคณะไม่ตรง
    return bool(missing_fields(doc))
